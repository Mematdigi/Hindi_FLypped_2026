<script>
document.addEventListener('DOMContentLoaded', function () {
  const searchOpenBtn  = document.getElementById('searchOpenBtn');
  const searchCloseBtn = document.getElementById('searchCloseBtn');
  const hdrSearchForm  = document.getElementById('hdrSearchForm');
  const hdrSearchInput = document.getElementById('hdrSearchInput');

  if (searchOpenBtn && hdrSearchForm) {
    searchOpenBtn.addEventListener('click', function () {
      hdrSearchForm.classList.remove('d-none');
      hdrSearchForm.classList.add('d-flex');
      searchOpenBtn.classList.add('d-none');
      if (hdrSearchInput) hdrSearchInput.focus();
    });
  }
  if (searchCloseBtn && hdrSearchForm) {
    searchCloseBtn.addEventListener('click', function () {
      hdrSearchForm.classList.add('d-none');
      hdrSearchForm.classList.remove('d-flex');
      searchOpenBtn.classList.remove('d-none');
      if (hdrSearchInput) hdrSearchInput.value = '';
    });
  }
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && hdrSearchForm && !hdrSearchForm.classList.contains('d-none')) {
      searchCloseBtn.click();
    }
  });

  const mobileNavBtn = document.getElementById('mobileNavToggle');
  const navMenu      = document.getElementById('navbarMenu');
  if (mobileNavBtn && navMenu) {
    mobileNavBtn.addEventListener('click', function (e) {
      e.stopPropagation();
      navMenu.classList.toggle('show');
    });
    navMenu.querySelectorAll('.nav-link').forEach(l => {
      l.addEventListener('click', () => navMenu.classList.remove('show'));
    });
    document.addEventListener('click', function (e) {
      if (!navMenu.contains(e.target) && e.target !== mobileNavBtn) {
        navMenu.classList.remove('show');
      }
    });
  }
});
</script> 
